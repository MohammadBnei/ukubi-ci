#!/usr/bin/env bash
# Runs the C2 reusable workflows' own run blocks (extracted with yq, never
# copied) against throwaway repos and fixtures. Needs bash, yq v4, git, jq;
# go for the gofmt and vettool cases (skipped with a notice without it).
# Usage: test/reusable.sh [path/to/.github/workflows]
set -uo pipefail
W=${1:-$(dirname "$0")/../.github/workflows}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
# Same result locally and on a runner: no global config (signing, identity).
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@t.invalid GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@t.invalid
fails=0
ok()  { echo "ok   $1"; }
bad() { echo "FAIL $1"; fails=$((fails + 1)); }
# extract <file> <step name> <out>: the run block, or stop (a renamed step must fail loudly).
extract() {
  yq ".jobs[].steps[] | select(.name == \"$2\") | .run" "$W/$1" > "$3"
  [ -s "$3" ] || { echo "FAIL extract '$2' from $1"; exit 1; }
}
# expect <want: 0 pass | 1 fail> <name> <rc> [output] [want substring]
expect() {
  local got=$(( $3 != 0 ))
  if [ "$got" != "$1" ]; then bad "$2 (rc=$3) ${4:-}"; return; fi
  if [ -n "${5:-}" ] && [[ "${4:-}" != *"$5"* ]]; then bad "$2: want '$5' in: ${4:-}"; return; fi
  ok "$2"
}

# 0. Shape: least privilege, inputs through env only, optional steps gated.
for f in go-checks bun-checks rust-checks image-build trailers; do
  p=$(yq -o=json -I0 '[.jobs[].permissions] | unique' "$W/$f.yml")
  if [ "$p" = '[{"contents":"read"}]' ]; then ok "$f: every job is contents: read"; else bad "$f: permissions $p"; fi
  # shellcheck disable=SC2016 # a literal ${{, not a shell expansion
  if yq '.jobs[].steps[].run | select(. != null)' "$W/$f.yml" | grep -qF '${{'; then
    bad "$f: an expression inside a run block"
  else ok "$f: no expression inside a run block"; fi
done
gate() { # file step want-if
  local got; got=$(yq ".jobs[].steps[] | select(.name == \"$2\") | .if // \"\"" "$W/$1.yml")
  if [ "$got" = "$3" ]; then ok "$1: '$2' if: ${3:-always}"; else bad "$1: '$2' if is '$got', want '$3'"; fi
}
gate go-checks gofmt ''
gate go-checks 'go vet' ''
gate go-checks 'go test' ''
gate go-checks Pre-test "inputs.pre-test != ''"
gate go-checks golangci-lint "inputs.golangci-lint-version != ''"
gate go-checks 'go vet -vettool' "inputs.vettool != ''"
gate bun-checks Install ''
gate bun-checks Typecheck "inputs.typecheck-script != ''"
gate bun-checks Test "inputs.test-script != ''"
gate bun-checks Build "inputs.build-script != ''"
gate bun-checks 'Dist is fresh' "inputs.dist != ''"
gate rust-checks 'Install apt packages' "inputs.apt-packages != ''"
gate rust-checks Format ''
gate rust-checks Clippy ''
gate rust-checks Audit ''

# 1. image-build's tag and Build steps are image.yml's, env included.
sel='.jobs[].steps[] | select(.name == "Build" or .id == "tag")'
if d=$(diff <(yq -o=json -I0 "$sel" "$W/image.yml") <(yq -o=json -I0 "$sel" "$W/image-build.yml")); then
  ok "image-build: tag and Build steps == image.yml"
else bad "image-build: tag and Build steps drifted from image.yml: $d"; fi

# 2. trailers. One repo: BASE0 is itself dirty (the base side is never scanned).
extract trailers.yml "Check commits and PR text" "$T/trailers.sh"
R=$T/repo; git init -q -b main "$R"
c() { git -C "$R" -c commit.gpgsign=false commit -q --allow-empty -m "$1"; }
c 'chore: root'
c "$(printf 'chore: dirty base\n\nClaude-Session: on-base')"
BASE0=$(git -C "$R" rev-parse HEAD)
git -C "$R" update-ref refs/remotes/origin/main "$BASE0"
opts() { EV=pull_request B=$BASE0 TITLE='feat: ok' BODY='' CONV=false PREFIXES='' AGENT=any EXTRA=''; }
fresh() { git -C "$R" checkout -q --detach "$BASE0"; opts; }
tr_run() { # want name [want substring]
  local rc=0 out
  out=$(cd "$R" && EVENT=$EV BASE=$B HEAD=$(git rev-parse HEAD) BASE_REF=main PR_TITLE=$TITLE PR_BODY=$BODY \
    CONVENTIONAL=$CONV ALLOW_PREFIXES=$PREFIXES AGENT_TRAILERS=$AGENT EXTRA_BANNED=$EXTRA \
    bash "$T/trailers.sh" 2>&1) || rc=$?
  expect "$1" "trailers: $2" "$rc" "$out" "${3:-}"
}
fresh; c 'feat(api): add a thing'; CONV=true
tr_run 0 "clean conventional commit passes (positive control; dirty BASE not scanned)"
for s in 'Co-Authored-By: Claude <noreply@anthropic.com>' 'see https://claude.ai/code/x' 'see https://www.claude.com/x' \
         'Claude-Session: abc' '  claude-session: abc' 'generated with Claude Code' '🤖 Generated with [Claude Code](x)' \
         'Generated by Claude' 'Co-Authored-By: Claude <a@b>' 'Co-Authored-By: Bot <x@anthropic.com>' \
         'Co-Authored-By: someone (Opus 4) <a@b>' 'Co-Authored-By: x (gpt-5) <a@b>' 'mail noreply@anthropic.com'; do
  fresh; c "$(printf 'feat: ok\n\n%s' "$s")"; tr_run 1 "banned: $s" "vendor attribution"
done
for s in 'Agent-Session: x' 'Ban bare "Claude-Session:" lines too.' 'Code generated with stringer.' \
         'the footer as "Generated with [x"' 'claude.ai without a slash'; do
  fresh; c "$(printf 'feat: ok\n\n%s' "$s")"; tr_run 0 "false positive passes: $s"
done
fresh; GIT_AUTHOR_EMAIL=noreply@anthropic.com c 'feat: ok'; tr_run 1 "author email refused" "vendor attribution"
fresh; GIT_COMMITTER_EMAIL=noreply@anthropic.com c 'feat: ok'; tr_run 1 "committer email refused" "vendor attribution"
# Stale BASE: main moved on (with a dirty commit) and the PR merged it in.
fresh; git -C "$R" checkout -q -b later; c "$(printf 'chore: later on main\n\nClaude-Session: later')"
LATER=$(git -C "$R" rev-parse HEAD); git -C "$R" update-ref refs/remotes/origin/main "$LATER"
git -C "$R" checkout -q --detach "$BASE0"; c 'feat: pr work'
git -C "$R" -c commit.gpgsign=false merge -q --no-ff -m "Merge branch 'main' into pr" "$LATER"
CONV=true; tr_run 0 "stale BASE: commits already on main are not scanned"
git -C "$R" update-ref refs/remotes/origin/main "$BASE0"
fresh; c 'feat: side'; SIDE=$(git -C "$R" rev-parse HEAD)
fresh; c 'add a thing'; tr_run 0 "non-conventional subject passes when conventional=false"
CONV=true; tr_run 1 "non-conventional subject refused when conventional=true" "not a Conventional Commit"
fresh; c 'Revert "feat: add a thing"'; CONV=true; tr_run 0 "git's Revert subject passes conventional"
fresh; c 'fixup! feat: add a thing'; CONV=true; tr_run 1 "fixup! refused by conventional"
fresh; c 'content: 2026-10-28 entry'; CONV=true; PREFIXES=$(printf 'journal: \ncontent: '); tr_run 0 "allow-prefix exempts the conventional rule"
fresh; c "$(printf 'content: entry\n\nClaude-Session: x')"; CONV=true; PREFIXES='content: '
tr_run 1 "allow-prefix never exempts the ban" "vendor attribution"
fresh; c 'feat: one'; git -C "$R" -c commit.gpgsign=false merge -q --no-ff -m "Merge branch 'x' into y" "$SIDE"
CONV=true; TITLE='feat: x'; tr_run 0 "merge subject passes conventional"
fresh; c 'feat: one'; git -C "$R" -c commit.gpgsign=false merge -q --no-ff -m "$(printf 'Merge x\n\nClaude-Session: x')" "$SIDE"
tr_run 1 "merge carrying a banned trailer refused" "vendor attribution"
fresh; c 'feat: ok'; CONV=true; TITLE='Add a thing'; tr_run 1 "bad PR title refused when conventional" "PR title"
fresh; c 'feat: ok'; CONV=true; TITLE='feat: add a thing (#12)'; tr_run 0 "squash title with (#N) passes"
fresh; c 'feat: ok'; TITLE='Add a thing'; tr_run 0 "bad PR title passes when conventional=false"
fresh; c 'feat: ok'; BODY=$(printf 'Summary\n\nhttps://claude.ai/code/session_x'); tr_run 1 "PR body URL refused" "PR title or body"
fresh; c 'feat: ok'; BODY=$(printf 'Summary\n\n🤖 Generated with [Claude Code](x)'); tr_run 1 "PR body footer refused" "PR title or body"
fresh; c 'add a thing'; EV=push; B=''; CONV=true; tr_run 0 "push event is a no-op" "no-op"
fresh; c 'feat: ok'; B=''; tr_run 1 "empty BASE fails closed" "base and head"
fresh; c 'feat: ok'; B=0123456789abcdef0123456789abcdef01234567; tr_run 1 "BASE not in the repo fails closed" "cannot list"
fresh; B=$BASE0; tr_run 1 "BASE == HEAD fails closed" "no commits"
AC='Co-Authored-By: ukubi-claude-macbook <noreply@bnei.dev>'; AS='Agent-Session: ukubi-std-x'
fresh; c "$(printf 'feat: ok\n\n%s\n%s' "$AC" "$AS")"; AGENT=pair; tr_run 0 "pair: both well-formed trailers pass"
fresh; c 'feat: ok'; AGENT=pair; tr_run 0 "pair: a human commit with neither passes"
fresh; c "$(printf 'feat: ok\n\n%s' "$AC")"; AGENT=pair; tr_run 1 "pair: Co-Authored-By alone refused" "both well-formed"
fresh; c "$(printf 'feat: ok\n\n%s\nAgent-Session: two words' "$AC")"; AGENT=pair; tr_run 1 "pair: malformed Agent-Session refused" "both well-formed"
fresh; c "$(printf 'feat: ok\n\n%s\n%s' "$AC" "$AS")"; AGENT=forbid; tr_run 1 "forbid: agent trailers refused" "forbids"
fresh; c 'feat: ok'; AGENT=forbid; tr_run 0 "forbid: a human commit passes"
fresh; c 'feat: ok'; AGENT=sometimes; tr_run 1 "bad agent-trailers value refused" "agent-trailers"
fresh; c "$(printf 'feat: ok\n\nCode generated with sqlc.')"; EXTRA='generated with'; tr_run 1 "extra-banned refuses wird's unanchored form" "vendor attribution"
fresh; c 'feat: ok'; EXTRA='('; tr_run 1 "invalid extra-banned refused" "not a valid ERE"

# 3. bun-checks: the pin and dist preconditions, then dist freshness.
extract bun-checks.yml "Check inputs" "$T/bun-in.sh"
extract bun-checks.yml "Dist is fresh" "$T/bun-dist.sh"
P=$T/pkg; git init -q -b main "$P"; mkdir -p "$P/dist"; echo 'x' > "$P/dist/index.js"
git -C "$P" add dist; git -C "$P" -c commit.gpgsign=false commit -q -m 'chore: dist'
bun_in() { # want name packageManager-json build-script dist [substring]
  local rc=0 out
  if [ "$3" = - ]; then echo '{}' > "$P/package.json"; else printf '{"packageManager": %s}' "$3" > "$P/package.json"; fi
  : > "$T/gh-out"
  out=$(cd "$P" && GITHUB_OUTPUT=$T/gh-out BUILD_SCRIPT=$4 DIST=$5 bash "$T/bun-in.sh" 2>&1) || rc=$?
  expect "$1" "bun pin: $2" "$rc" "$out" "${6:-}"
}
bun_in 0 'bun@1.4.2 passes' '"bun@1.4.2"' build ''
if [ "$(cat "$T/gh-out")" = version=1.4.2 ]; then ok "bun pin: outputs version=1.4.2"; else bad "bun pin: output '$(cat "$T/gh-out")'"; fi
for v in '"bun@^1.4.2"' '"bun@latest"' '"bun@1.4"' '"npm@10.0.0"' '"bun@1.4.2 "' '-'; do
  bun_in 1 "$v refused" "$v" build '' "exactly bun@X.Y.Z"
done
bun_in 0 'tracked dist passes' '"bun@1.4.2"' build dist
bun_in 1 'dist with empty build-script refused' '"bun@1.4.2"' '' dist "build-script is empty"
bun_in 1 'dist naming untracked path refused' '"bun@1.4.2"' build distt "tracks no files"
dist_run() { # want name
  local rc=0 out; out=$(cd "$P" && DIST=dist bash "$T/bun-dist.sh" 2>&1) || rc=$?
  expect "$1" "dist: $2" "$rc" "$out"
}
rm -f "$P/package.json"; dist_run 0 "clean dist passes"
echo 'y' > "$P/dist/index.js"; dist_run 1 "modified tracked file refused"; git -C "$P" checkout -q -- dist
echo 'z' > "$P/dist/chunk.js"; dist_run 1 "untracked file in dist refused"; rm "$P/dist/chunk.js"
echo 'z' > "$P/elsewhere.txt"; dist_run 0 "a change outside dist is not dist's business"

# 4. rust-checks: inputs, and the audit-ignore list (a fake cargo prints its args).
extract rust-checks.yml "Check inputs" "$T/rust-in.sh"
extract rust-checks.yml "Audit" "$T/audit.sh"
C=$T/crate; mkdir -p "$C" "$T/bin"
rust_in() { # want name toolchain-file? apt [substring]
  local rc=0 out; rm -f "$C/rust-toolchain.toml"; [ "$3" = yes ] && : > "$C/rust-toolchain.toml"
  out=$(cd "$C" && APT_PACKAGES=$4 bash "$T/rust-in.sh" 2>&1) || rc=$?
  expect "$1" "rust inputs: $2" "$rc" "$out" "${5:-}"
}
rust_in 0 "toolchain file, no apt packages" yes ''
rust_in 0 "apt protobuf-compiler libssl-dev passes" yes 'protobuf-compiler libssl-dev'
rust_in 1 "missing rust-toolchain.toml refused" no '' "rust-toolchain.toml is required"
rust_in 1 "apt name with a ; refused" yes 'protobuf-compiler;id' "bad apt package"
rust_in 1 "apt option refused" yes '-o Debug::x=1' "bad apt package"
printf '#!/bin/sh\necho "cargo $*"\n' > "$T/bin/cargo"; chmod +x "$T/bin/cargo"
audit() { # want name ignore-list want-output-or-substring
  local rc=0 out; out=$(PATH="$T/bin:$PATH" AUDIT_IGNORE=$3 bash "$T/audit.sh" 2>&1) || rc=$?
  expect "$1" "audit-ignore: $2" "$rc" "$out" "$4"
  if [ "$1" = 0 ] && [ "$out" != "$4" ]; then bad "audit-ignore: $2: args '$out' want '$4'"; fi
}
audit 0 "empty runs plain cargo audit" '' 'cargo audit'
audit 0 "two ids become --ignore args" "$(printf 'RUSTSEC-2026-0414\nRUSTSEC-2025-0001')" \
  'cargo audit --ignore RUSTSEC-2026-0414 --ignore RUSTSEC-2025-0001'
audit 0 "blank lines and spaces skipped" "$(printf '\n  RUSTSEC-2026-0414  \n\n')" 'cargo audit --ignore RUSTSEC-2026-0414'
audit 1 "short id refused" 'RUSTSEC-26-1' 'RUSTSEC-YYYY-NNNN'
audit 1 "--json injection refused" '--json' 'RUSTSEC-YYYY-NNNN'
audit 1 "id with a trailing option refused" 'RUSTSEC-2026-0414 --json' 'RUSTSEC-YYYY-NNNN'

# 5. go-checks: inputs, gofmt, and the vettool path.
extract go-checks.yml "Check inputs" "$T/go-in.sh"
extract go-checks.yml "gofmt" "$T/gofmt.sh"
extract go-checks.yml "go vet -vettool" "$T/vettool.sh"
M=$T/mod; git init -q -b main "$M"; printf 'module example.com/m\n\ngo 1.24\n' > "$M/go.mod"
go_in() { # want name lint vettool test-flags [substring]
  local rc=0 out; out=$(cd "$M" && LINT_VERSION=$3 VETTOOL=$4 TEST_FLAGS=$5 bash "$T/go-in.sh" 2>&1) || rc=$?
  expect "$1" "go inputs: $2" "$rc" "$out" "${6:-}"
}
go_in 0 "all empty passes" '' '' ''
go_in 0 "pinned lint, vettool and -p 1 pass" v2.14.0 golang.org/x/tools/go/analysis/passes/nilness/cmd/nilness@v0.52.0 '-p 1'
go_in 1 "lint latest refused" latest '' '' "vX.Y.Z"
go_in 1 "lint without v refused" 2.14.0 '' '' "vX.Y.Z"
go_in 1 "vettool @latest refused" '' example.com/x@latest '' "never @latest"
go_in 1 "vettool without a version refused" '' example.com/x '' "never @latest"
go_in 1 "test-flags with ; refused" '' '' '-p 1; id' "test-flags"
# shellcheck disable=SC2016 # a literal $(, the payload under test
go_in 1 "test-flags with \$( refused" '' '' '-run $(id)' "test-flags"
mv "$M/go.mod" "$M/go.mod.x"; go_in 1 "no go.mod refused" '' '' '' "Go module"; mv "$M/go.mod.x" "$M/go.mod"
if command -v go >/dev/null && command -v gofmt >/dev/null; then
  gofmt_run() { local rc=0 out; out=$(cd "$M" && bash "$T/gofmt.sh" 2>&1) || rc=$?; expect "$1" "gofmt: $2" "$rc" "$out" "${3:-}"; }
  gofmt_run 0 "no .go files passes (does not hang)"
  printf 'package m\n\nfunc F() int { return 1 }\n' > "$M/m.go"; git -C "$M" add m.go
  gofmt_run 0 "formatted file passes"
  printf 'package m\n\nfunc F() int {\nreturn 1\n}\n' > "$M/m.go"
  gofmt_run 1 "unformatted tracked file refused" "m.go"
  printf 'package m\n\nfunc F() int { return 1 }\n' > "$M/m.go"
  vt_run() { local rc=0 out; out=$(cd "$M" && RUNNER_TEMP=$T/rt VETTOOL=golang.org/x/tools/go/analysis/passes/nilness/cmd/nilness@v0.52.0 bash "$T/vettool.sh" 2>&1) || rc=$?; expect "$1" "vettool: $2" "$rc" "$out" "${3:-}"; }
  vt_run 0 "nilness passes on clean code"
  printf 'package m\n\nfunc G(p *int) int {\n\tif p == nil {\n\t\treturn *p\n\t}\n\treturn 0\n}\n' > "$M/g.go"
  vt_run 1 "nilness flags a planted nil dereference" "nil dereference"
else
  echo "skip go absent: gofmt and vettool cases not run"
fi

echo "failures: $fails"
[ "$fails" = 0 ]
